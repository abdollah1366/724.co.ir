START_B, START_C, STOP = 104, 105, 106


def encode(text):
    """کدهای Code 128 (با رقم کنترل). رشته عددی با طول زوج با مجموعه C، بقیه با مجموعه B."""
    if text.isdigit() and len(text) % 2 == 0:
        codes = [START_C] + [int(text[i:i + 2]) for i in range(0, len(text), 2)]
    else:
        if any(not 32 <= ord(ch) <= 126 for ch in text):
            raise ValueError("Code 128-B فقط نویسه‌های ASCII قابل چاپ را می‌پذیرد.")
        codes = [START_B] + [ord(ch) - 32 for ch in text]
    checksum = (codes[0] + sum(i * c for i, c in enumerate(codes[1:], start=1))) % 103
    return codes + [checksum, STOP]


def svg(text, height=40, module=2):
    bits = "".join(PATTERNS[c] for c in encode(text))
    quiet = 10 * module
    width = len(bits) * module + 2 * quiet
    rects = []
    x = quiet
    run = 0
    for i, bit in enumerate(bits + "0"):
        if bit == "1":
            run += 1
            continue
        if run:
            start = x + (i - run) * module
            rects.append(f'<rect x="{start}" y="0" width="{run * module}" height="{height}"/>')
            run = 0
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}" '
        f'role="img" aria-label="{text}"><rect width="100%" height="100%" fill="#fff"/><g fill="#000">{"".join(rects)}</g></svg>'
    )
